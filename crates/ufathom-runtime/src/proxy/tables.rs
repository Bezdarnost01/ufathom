//! The export tables of the system DLLs a generated SDK can pose as.
//!
//! Each [`Preset`] lists every export of one system DLL: its name (absent for
//! an export that has only an ordinal), its ordinal, and whether the DLL marks
//! it `PRIVATE` in a module-definition file. The lists were read from the
//! export directories of the system DLLs, and a test compares them with the
//! DLLs of the machine it runs on, so a Windows update that adds an export is
//! reported by name.
//!
//! This file is plain data and uses nothing but `core` and `alloc`: the code
//! generator compiles it as well, to write the `.def` file the linker needs to
//! export these names at the right ordinals.

/// One export of a system DLL.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Export {
    /// The exported name. `None` for an export that has only an ordinal.
    pub name: Option<&'static str>,
    /// The ordinal the system DLL assigns to the export. Games may import by
    /// ordinal, so the proxy keeps it.
    pub ordinal: u16,
    /// Whether the export is `PRIVATE` in a module-definition file: it stays
    /// out of the import library. This is only a build-time property.
    pub private: bool,
}

/// The exports of one system DLL, for one `proxy-*` feature.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Preset {
    /// The file stem of the system DLL, lower case, as in `dsound` for
    /// `dsound.dll`. It is also the suffix of the Cargo feature.
    pub dll: &'static str,
    /// The Cargo feature that enables the preset, as in `proxy-dsound`.
    pub feature: &'static str,
    /// Every export, in ordinal order.
    pub exports: &'static [Export],
}

impl Preset {
    /// The file name of the system DLL, as in `dsound.dll`.
    #[must_use]
    pub fn file_name(&self) -> String {
        format!("{}.dll", self.dll)
    }

    /// The name of the assembly stub that forwards the export with this
    /// ordinal. The `.def` file maps the public name to it.
    #[must_use]
    pub fn stub_symbol(&self, ordinal: u16) -> String {
        format!("ufathom_proxy_{}_{ordinal}", self.dll)
    }

    /// The largest ordinal of any export.
    #[must_use]
    pub const fn max_ordinal(&self) -> u16 {
        let mut largest = 0;
        let mut rest = self.exports;
        while let [export, tail @ ..] = rest {
            if export.ordinal > largest {
                largest = export.ordinal;
            }
            rest = tail;
        }
        largest
    }

    /// The module-definition file for the linker: every export by its public
    /// name and ordinal, mapped to its stub. An export with only an ordinal is
    /// written `NONAME`.
    #[must_use]
    pub fn def_file(&self) -> String {
        let mut text = format!(
            "; Exports of the system {}, forwarded to it by the `{}` feature.\n\
             ; Generated by ufathom-codegen from the tables in ufathom-runtime. Do not edit.\n\
             EXPORTS\n",
            self.file_name(),
            self.feature
        );
        for export in self.exports {
            let stub = self.stub_symbol(export.ordinal);
            let ordinal = export.ordinal;
            let line = match (export.name, export.private) {
                (Some(name), false) => format!("    {name}={stub} @{ordinal}\n"),
                (Some(name), true) => format!("    {name}={stub} @{ordinal} PRIVATE\n"),
                (None, _) => format!("    {stub} @{ordinal} NONAME\n"),
            };
            text.push_str(&line);
        }
        text
    }
}

