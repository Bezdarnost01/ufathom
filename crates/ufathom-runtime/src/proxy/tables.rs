macro_rules! define_presets {
    ($(
        ($const_name:ident, $id:ident, $dll:literal, $feature:literal, [
            $( ($name:expr, $ordinal:literal, $private:literal) ),* $(,)?
        ])
    ),* $(,)?) => {
        $(
            #[doc = concat!("The exports of the system `", $dll, ".dll`.")]
            pub const $const_name: Preset = Preset {
                dll: $dll,
                feature: $feature,
                exports: &[
                    $( Export { name: $name, ordinal: $ordinal, private: $private } ),*
                ],
            };
        )*

        /// Every preset, in the order of the `proxy-*` features.
        pub const PRESETS: &[Preset] = &[$($const_name),*];
    };
}

for_each_preset!(define_presets);
