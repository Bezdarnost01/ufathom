//! Prints planned types as Rust source.

use std::fmt::Write as _;

use crate::build::{Built, ModuleInfo, PlannedEnum, PlannedField, PlannedFunction, PlannedStruct};
use crate::names::doc_text;
use crate::planner::{BaseMode, Item, Plan};

/// Writes formatted text into a `String`. Writing to a `String` cannot fail.
macro_rules! w {
    ($out:expr, $($arg:tt)*) => {{
        let _ = write!($out, $($arg)*);
    }};
}
macro_rules! wl {
    ($out:expr) => {{
        $out.push('\n');
    }};
    ($out:expr, $($arg:tt)*) => {{
        let _ = writeln!($out, $($arg)*);
    }};
}

const RT_USE: &str = "use ::ufathom_runtime as rt;";

/// The text of one package module.
pub(crate) fn module_source(built: &Built, module: &ModuleInfo) -> String {
    let mut out = String::new();
    wl!(out, "//! Package `{}`.", doc_text(&module.package));
    wl!(out, "//!");
    wl!(out, "//! Generated by ufathom-codegen. Do not edit.");
    wl!(out);
    wl!(out, "{RT_USE}");
    for e in built.enums.iter().filter(|e| e.module == module.name) {
        wl!(out);
        emit_enum(&mut out, e);
    }
    for s in built.structs.iter().filter(|s| s.module == module.name) {
        wl!(out);
        emit_struct(&mut out, s);
        for f in &s.functions {
            wl!(out);
            emit_params(&mut out, f);
        }
    }
    out
}

/// The text of `src/lib.rs`.
pub(crate) fn lib_source(built: &Built, engine: Option<&str>) -> String {
    let mut out = String::new();
    wl!(
        out,
        "//! Rust SDK generated by ufathom-codegen. Do not edit."
    );
    if let Some(version) = engine {
        wl!(out, "//!");
        wl!(out, "//! Engine version: {}.", doc_text(version));
    }
    wl!(out, "//!");
    wl!(
        out,
        "//! Every type is `#[repr(C)]` with explicit padding and asserts its size,"
    );
    wl!(
        out,
        "//! alignment and field offsets at compile time. A package is a module behind a"
    );
    wl!(
        out,
        "//! Cargo feature with the same name; a feature enables the packages it needs."
    );
    wl!(out);
    wl!(out, "#![allow(");
    wl!(out, "    non_camel_case_types,");
    wl!(out, "    non_snake_case,");
    wl!(out, "    non_upper_case_globals,");
    wl!(out, "    dead_code,");
    wl!(out, "    unused_imports,");
    wl!(out, "    clippy::all,");
    wl!(out, "    clippy::pedantic,");
    wl!(out, "    clippy::nursery");
    wl!(out, ")]");
    wl!(out);
    wl!(out, "/// The `FName` of this build.");
    wl!(out, "pub type FName = {};", built.fname.alias_target);
    for m in &built.modules {
        wl!(out);
        wl!(out, "#[cfg(feature = \"{}\")]", m.name);
        wl!(out, "pub mod {};", m.name);
    }
    out
}

/// The text of `Cargo.toml`.
pub(crate) fn cargo_source(
    built: &Built,
    crate_name: &str,
    crate_version: &str,
    runtime: &str,
    workspace: &str,
) -> String {
    let mut out = String::new();
    wl!(out, "[package]");
    wl!(out, "name = {}", toml_string(crate_name));
    wl!(out, "version = {}", toml_string(crate_version));
    wl!(out, "edition = \"2021\"");
    wl!(
        out,
        "description = \"Rust SDK generated by ufathom-codegen.\""
    );
    wl!(out, "publish = false");
    wl!(out);
    wl!(out, "[dependencies]");
    wl!(out, "ufathom-runtime = {runtime}");
    wl!(out);
    wl!(out, "[features]");
    wl!(out, "default = [\"all\"]");
    let all: Vec<String> = built.modules.iter().map(|m| toml_string(&m.name)).collect();
    wl!(out, "all = [{}]", all.join(", "));
    for m in &built.modules {
        let deps: Vec<String> = m.deps.iter().map(|d| toml_string(d)).collect();
        wl!(out, "{} = [{}]", m.name, deps.join(", "));
    }
    wl!(out);
    wl!(
        out,
        "# This crate is its own workspace, so it builds from any directory."
    );
    wl!(out, "[workspace]");
    out.push_str(workspace);
    out
}

/// A TOML basic string.
pub(crate) fn toml_string(text: &str) -> String {
    let mut out = String::from("\"");
    for c in text.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            c if c.is_control() => w!(out, "\\u{:04x}", u32::from(c)),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

fn emit_enum(out: &mut String, e: &PlannedEnum) {
    let name = &e.rust_name;
    let int = e.int;
    wl!(out, "/// Enum `{}`.", doc_text(&e.path));
    wl!(out, "///");
    wl!(
        out,
        "/// A newtype over `{int}`: a value the dump does not list is valid."
    );
    wl!(out, "#[repr(transparent)]");
    wl!(
        out,
        "#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]"
    );
    wl!(out, "pub struct {name}(pub {int});");
    wl!(out);
    wl!(out, "impl {name} {{");
    for (const_name, value) in &e.consts {
        wl!(out, "    pub const {const_name}: Self = Self({value});");
    }
    wl!(out);
    wl!(
        out,
        "    /// The name of the enumerator, if the value is one the dump lists."
    );
    wl!(
        out,
        "    pub const fn name(self) -> Option<&'static str> {{"
    );
    wl!(out, "        match self.0 {{");
    for (value, text) in &e.names {
        wl!(out, "            {value} => Some({text:?}),");
    }
    wl!(out, "            _ => None,");
    wl!(out, "        }}");
    wl!(out, "    }}");
    wl!(out, "}}");
    wl!(out);
    wl!(out, "impl ::core::fmt::Debug for {name} {{");
    wl!(
        out,
        "    fn fmt(&self, f: &mut ::core::fmt::Formatter<'_>) -> ::core::fmt::Result {{"
    );
    wl!(out, "        match self.name() {{");
    wl!(
        out,
        "            Some(name) => write!(f, \"{name}::{{}}\", name),"
    );
    wl!(
        out,
        "            None => write!(f, \"{name}({{}})\", self.0),"
    );
    wl!(out, "        }}");
    wl!(out, "    }}");
    wl!(out, "}}");
    wl!(out);
    wl!(
        out,
        "// SAFETY: a transparent integer, valid for every bit pattern."
    );
    wl!(out, "unsafe impl rt::Pod for {name} {{}}");
    wl!(out);
    wl!(
        out,
        "const _: () = assert!(::core::mem::size_of::<{name}>() == ::core::mem::size_of::<{int}>());"
    );
}

/// The Rust type of a field as written in the struct.
fn field_type(f: &PlannedField, item_len: Option<u32>) -> String {
    match (&f.resolved, f.is_bytes) {
        (Some(r), false) => {
            if f.count > 1 {
                format!("[{}; {}]", r.rust, f.count)
            } else {
                r.rust.clone()
            }
        }
        _ => format!(
            "[u8; {}]",
            item_len.unwrap_or_else(|| f.element_size.saturating_mul(f.count))
        ),
    }
}

fn field_doc(f: &PlannedField) -> String {
    let mut text = format!("Offset {:#x}, `{}`.", f.offset, doc_text(&f.ty_display));
    if let Some(note) = &f.note {
        text.push_str(&format!(" Not exact: {}.", doc_text(note)));
    }
    text
}

/// Writes the struct, its `Pod` impl and its compile-time assertions.
#[allow(
    clippy::too_many_arguments,
    reason = "one printer shared by classes and parameter blocks"
)]
fn emit_layout(
    out: &mut String,
    name: &str,
    doc: &[String],
    size: u32,
    plan: &Plan,
    fields: &[PlannedField],
    base_path: Option<&str>,
) {
    for line in doc {
        if line.is_empty() {
            wl!(out, "///");
        } else {
            wl!(out, "/// {line}");
        }
    }
    wl!(out, "#[repr(C, align({}))]", plan.align);
    wl!(out, "#[derive(Clone, Copy, Debug)]");
    wl!(out, "pub struct {name} {{");
    if plan.base == BaseMode::Embedded {
        if let Some(base) = base_path {
            wl!(out, "    /// The parent class.");
            wl!(out, "    pub base: {base},");
        }
    }
    for item in &plan.items {
        match item {
            Item::Pad { offset, len } => {
                wl!(out, "    /// Padding at {offset:#x}.");
                wl!(out, "    pub _pad_{offset:#06x}: [u8; {len}],");
            }
            Item::Typed { field, .. } => {
                if let Some(f) = fields.get(*field) {
                    wl!(out, "    /// {}", field_doc(f));
                    wl!(
                        out,
                        "    pub {}: {},",
                        f.rust_field.as_deref().unwrap_or("_"),
                        field_type(f, None)
                    );
                }
            }
            Item::Bytes { field, len, .. } => {
                if let Some(f) = fields.get(*field) {
                    wl!(out, "    /// {}", field_doc(f));
                    wl!(
                        out,
                        "    pub {}: {},",
                        f.rust_field.as_deref().unwrap_or("_"),
                        field_type(f, Some(*len))
                    );
                }
            }
            Item::Bits { offset, len, bits } => {
                let names: Vec<String> = bits
                    .iter()
                    .filter_map(|b| fields.get(b.field))
                    .map(|f| format!("`{}`", doc_text(&f.name)))
                    .collect();
                wl!(
                    out,
                    "    /// Storage of the bit-field booleans {} at {offset:#x}.",
                    names.join(", ")
                );
                let storage = bits
                    .first()
                    .and_then(|b| fields.get(b.field))
                    .and_then(|f| f.bit.as_ref())
                    .map_or("_bits", |b| b.storage_field.as_str());
                wl!(out, "    pub {storage}: [u8; {len}],");
            }
        }
    }
    wl!(out, "}}");
    wl!(out);
    wl!(
        out,
        "// SAFETY: every field is `Pod`, the type is `Copy`, and the explicit padding"
    );
    wl!(
        out,
        "// leaves no implicit padding: the size assertion below covers every byte."
    );
    wl!(out, "unsafe impl rt::Pod for {name} {{}}");
    wl!(out);
    wl!(out, "const _: () = {{");
    wl!(
        out,
        "    assert!(::core::mem::size_of::<{name}>() == {size:#x});"
    );
    wl!(
        out,
        "    assert!(::core::mem::align_of::<{name}>() == {});",
        plan.align
    );
    for item in &plan.items {
        match item {
            Item::Typed { field, offset, .. } | Item::Bytes { field, offset, .. } => {
                if let Some(rust) = fields.get(*field).and_then(|f| f.rust_field.as_deref()) {
                    wl!(
                        out,
                        "    assert!(::core::mem::offset_of!({name}, {rust}) == {offset:#x});"
                    );
                }
            }
            Item::Bits { offset, bits, .. } => {
                let storage = bits
                    .first()
                    .and_then(|b| fields.get(b.field))
                    .and_then(|f| f.bit.as_ref())
                    .map(|b| b.storage_field.as_str());
                if let Some(storage) = storage {
                    wl!(
                        out,
                        "    assert!(::core::mem::offset_of!({name}, {storage}) == {offset:#x});"
                    );
                }
            }
            Item::Pad { .. } => {}
        }
    }
    wl!(out, "}};");
}

fn emit_bit_accessors(out: &mut String, fields: &[PlannedField]) {
    for f in fields {
        let Some(b) = &f.bit else { continue };
        wl!(
            out,
            "    /// Bit `{}`: byte {:#x} of the owner, mask {:#04x}.",
            doc_text(&f.name),
            b.abs_offset,
            b.mask
        );
        wl!(out, "    pub fn {}(&self) -> bool {{", b.getter);
        wl!(
            out,
            "        self.{}[{}] & {:#04x}u8 != 0",
            b.storage_field,
            b.storage_byte,
            b.mask
        );
        wl!(out, "    }}");
        wl!(out);
        wl!(out, "    /// Sets bit `{}`.", doc_text(&f.name));
        wl!(out, "    pub fn {}(&mut self, value: bool) {{", b.setter);
        wl!(out, "        if value {{");
        wl!(
            out,
            "            self.{}[{}] |= {:#04x}u8;",
            b.storage_field,
            b.storage_byte,
            b.mask
        );
        wl!(out, "        }} else {{");
        wl!(
            out,
            "            self.{}[{}] &= !{:#04x}u8;",
            b.storage_field,
            b.storage_byte,
            b.mask
        );
        wl!(out, "        }}");
        wl!(out, "    }}");
        wl!(out);
    }
}

fn emit_struct(out: &mut String, s: &PlannedStruct) {
    let name = &s.rust_name;
    let kind = if s.is_class { "Class" } else { "Struct" };
    let mut doc = vec![
        format!("{kind} `{}`.", doc_text(&s.path)),
        String::new(),
        format!("Size {:#x}, alignment {}.", s.size, s.plan.align),
    ];
    if s.dump_size != s.size {
        doc.push(String::new());
        doc.push(format!(
            "The dump says {:#x} bytes; the type is padded at the end to a multiple of its alignment.",
            s.dump_size
        ));
    }
    match &s.plan.base {
        BaseMode::Cast(_, why) => {
            doc.push(String::new());
            doc.push(format!(
                "The parent is not a field ({}). `Deref` views it by a pointer cast.",
                doc_text(why)
            ));
        }
        BaseMode::Unavailable(_, why) => {
            doc.push(String::new());
            doc.push(format!(
                "The parent's bytes are plain padding and there is no `Deref` ({}).",
                doc_text(why)
            ));
        }
        BaseMode::None | BaseMode::Embedded => {}
    }
    emit_layout(
        out,
        name,
        &doc,
        s.size,
        &s.plan,
        &s.fields,
        s.base_path.as_deref(),
    );

    wl!(out);
    wl!(out, "// SAFETY: the type starts with itself.");
    wl!(out, "unsafe impl rt::IsA<{name}> for {name} {{}}");
    for a in &s.ancestors {
        wl!(out);
        wl!(
            out,
            "// SAFETY: the parent layout is the prefix of this type: embedded, or checked by a size assertion."
        );
        wl!(out, "unsafe impl rt::IsA<{a}> for {name} {{}}");
    }
    if let Some(base) = &s.base_path {
        match &s.plan.base {
            BaseMode::Embedded => {
                wl!(out);
                wl!(out, "impl ::core::ops::Deref for {name} {{");
                wl!(out, "    type Target = {base};");
                wl!(out, "    fn deref(&self) -> &{base} {{");
                wl!(out, "        &self.base");
                wl!(out, "    }}");
                wl!(out, "}}");
                wl!(out);
                wl!(out, "impl ::core::ops::DerefMut for {name} {{");
                wl!(out, "    fn deref_mut(&mut self) -> &mut {base} {{");
                wl!(out, "        &mut self.base");
                wl!(out, "    }}");
                wl!(out, "}}");
            }
            BaseMode::Cast(..) => {
                wl!(out);
                wl!(out, "impl ::core::ops::Deref for {name} {{");
                wl!(out, "    type Target = {base};");
                wl!(out, "    fn deref(&self) -> &{base} {{");
                wl!(
                    out,
                    "        // SAFETY: the parent is no larger and no more aligned than this type,"
                );
                wl!(
                    out,
                    "        // and starts at offset 0, so the cast stays inside `self`."
                );
                wl!(
                    out,
                    "        unsafe {{ &*(self as *const Self).cast::<{base}>() }}"
                );
                wl!(out, "    }}");
                wl!(out, "}}");
                wl!(out);
                wl!(out, "impl ::core::ops::DerefMut for {name} {{");
                wl!(out, "    fn deref_mut(&mut self) -> &mut {base} {{");
                wl!(out, "        // SAFETY: as for `deref`.");
                wl!(
                    out,
                    "        unsafe {{ &mut *(self as *mut Self).cast::<{base}>() }}"
                );
                wl!(out, "    }}");
                wl!(out, "}}");
            }
            BaseMode::Unavailable(..) | BaseMode::None => {}
        }
    }

    wl!(out);
    wl!(out, "impl {name} {{");
    let mut body = String::new();
    let out_outer = std::mem::replace(out, std::mem::take(&mut body));
    for f in &s.fields {
        let Some(c) = &f.const_name else { continue };
        if let Some((byte_offset, mask)) = f.bit_raw {
            wl!(out, "    /// Bit `{}` of the owner.", doc_text(&f.name));
            wl!(
                out,
                "    pub const {c}: rt::BitRef<Self> = rt::BitRef::new({:#x}, {mask:#04x});",
                f.offset + u32::from(byte_offset)
            );
        } else {
            wl!(
                out,
                "    /// Offset of `{}`: {}",
                doc_text(&f.name),
                field_doc(f)
            );
            wl!(
                out,
                "    pub const {c}: rt::FieldRef<Self, {}> = rt::FieldRef::new({:#x});",
                field_type(f, None),
                f.offset
            );
        }
        wl!(out);
    }
    emit_bit_accessors(out, &s.fields);
    for func in &s.functions {
        emit_wrapper(out, func);
    }
    let body = std::mem::replace(out, out_outer);
    out.push_str(body.trim_end_matches('\n'));
    wl!(out);
    wl!(out, "}}");
}

fn emit_wrapper(out: &mut String, f: &PlannedFunction) {
    wl!(out, "    /// Calls `{}` through `exec`.", doc_text(&f.path));
    wl!(out, "    ///");
    wl!(
        out,
        "    /// This wrapper fills the parameter block and hands it to the executor; it"
    );
    wl!(
        out,
        "    /// runs nothing itself. `this` must be the address of a live object of this"
    );
    wl!(
        out,
        "    /// class. Memory the engine allocates for return values or out parameters"
    );
    wl!(out, "    /// (strings, arrays) is not freed here.");
    let mut args = String::new();
    for p in &f.inputs {
        w!(args, ", {}: {}", p.arg, p.api_type);
    }
    let outputs: Vec<_> = f.ret.iter().chain(f.outs.iter()).collect();
    let ret_ty = match outputs.as_slice() {
        [] => "()".to_owned(),
        [one] => one.api_type.clone(),
        many => format!(
            "({})",
            many.iter()
                .map(|p| p.api_type.as_str())
                .collect::<Vec<_>>()
                .join(", ")
        ),
    };
    wl!(
        out,
        "    pub fn {}(this: rt::Ptr<Self>, exec: &impl rt::Executor{args}) -> Result<{ret_ty}, rt::CallError> {{",
        f.wrapper
    );
    wl!(
        out,
        "        let mut params: {} = rt::zeroed();",
        f.params_struct
    );
    for p in &f.inputs {
        let Some(field) = f.fields.get(p.field) else {
            continue;
        };
        if let Some(b) = &field.bit {
            wl!(out, "        params.{}({});", b.setter, p.arg);
        } else if let Some(name) = &field.rust_field {
            if p.is_ubool {
                wl!(out, "        params.{name} = rt::UBool::from({});", p.arg);
            } else {
                wl!(out, "        params.{name} = {};", p.arg);
            }
        }
    }
    wl!(
        out,
        "        exec.process_event(this.cast(), {:?}, rt::as_bytes_mut(&mut params))?;",
        f.path
    );
    let read = |p: &crate::build::ParamBinding| -> String {
        match f.fields.get(p.field) {
            Some(field) => match (&field.bit, &field.rust_field) {
                (Some(b), _) => format!("params.{}()", b.getter),
                (None, Some(name)) if p.is_ubool => format!("params.{name}.get()"),
                (None, Some(name)) => format!("params.{name}"),
                (None, None) => "()".to_owned(),
            },
            None => "()".to_owned(),
        }
    };
    let value = match outputs.as_slice() {
        [] => "()".to_owned(),
        [one] => read(one),
        many => format!(
            "({})",
            many.iter().map(|p| read(p)).collect::<Vec<_>>().join(", ")
        ),
    };
    wl!(out, "        Ok({value})");
    wl!(out, "    }}");
    wl!(out);
}

fn emit_params(out: &mut String, f: &PlannedFunction) {
    let doc = vec![
        format!("Parameter block of `{}`.", doc_text(&f.path)),
        String::new(),
        format!("Size {:#x}, alignment {}.", f.size, f.plan.align),
    ];
    emit_layout(
        out,
        &f.params_struct,
        &doc,
        f.size,
        &f.plan,
        &f.fields,
        None,
    );
    if f.fields.iter().any(|p| p.bit.is_some()) {
        wl!(out);
        wl!(out, "impl {} {{", f.params_struct);
        emit_bit_accessors(out, &f.fields);
        wl!(out, "}}");
    }
}
