//! What a generated SDK needs to pose as a system DLL: the `proxy-*` Cargo
//! features, one module-definition file per preset, and the build script that
//! hands the chosen file to the linker.
//!
//! The export lists come from `ufathom-runtime`: its table source is compiled
//! here, so the `.def` files and the assembly stubs of the runtime are written
//! from the same data.

use crate::output::OutFile;

#[allow(
    dead_code,
    reason = "the runtime's table source is shared whole; this crate reads part of it"
)]
#[path = "../../ufathom-runtime/src/proxy/tables.rs"]
mod tables;

use tables::{PRESETS, Preset};

/// Directory of the `.def` files inside the generated crate.
const DEF_DIR: &str = "proxy";

/// The Cargo feature of every preset, with the text of its manifest comment.
pub(crate) fn feature_lines() -> Vec<String> {
    let mut lines = vec![
        "# Name the DLL after a system DLL and put it beside the game: it exports that".to_owned(),
        "# DLL's functions, forwards them to the real one and waits for the engine".to_owned(),
        "# before `run`. Enable one of these, not several. Windows x86-64 only.".to_owned(),
    ];
    lines.extend(PRESETS.iter().map(|preset| {
        format!(
            "{} = [\"ufathom-runtime/{}\"]",
            preset.feature, preset.feature
        )
    }));
    lines
}

/// The `.def` file of every preset, under `proxy/`.
pub(crate) fn def_files() -> Vec<OutFile> {
    PRESETS
        .iter()
        .map(|preset| OutFile {
            path: def_path(preset),
            content: preset.def_file(),
            preserve_existing: false,
        })
        .collect()
}

fn def_path(preset: &Preset) -> String {
    format!("{DEF_DIR}/{}.def", preset.dll)
}

/// A `compile_error!` for every pair of `proxy-*` features, so enabling two
/// at once stops the build with a clear message.
pub(crate) fn exclusive_features_check() -> String {
    let mut pairs = Vec::new();
    for (index, first) in PRESETS.iter().enumerate() {
        for second in PRESETS.iter().skip(index + 1) {
            pairs.push(format!(
                "all(feature = \"{}\", feature = \"{}\")",
                first.feature, second.feature
            ));
        }
    }
    format!(
        "#[cfg(any(\n    {},\n))]\ncompile_error!(\n    \"enable only one `proxy-*` feature: a DLL takes the exports of one system DLL\"\n);\n",
        pairs.join(",\n    ")
    )
}

/// The text of the generated `build.rs`.
pub(crate) fn build_source() -> String {
    let mut table = String::new();
    for preset in PRESETS {
        let variable = format!(
            "CARGO_FEATURE_{}",
            preset.feature.to_uppercase().replace('-', "_")
        );
        table.push_str(&format!(
            "    (\"{variable}\", \"{}\"),\n",
            def_path(preset)
        ));
    }
    TEMPLATE.replace("{PROXIES}", &table)
}

const TEMPLATE: &str = r#"//! Build script generated by ufathom. Refreshed by later dumps.
//!
//! A `proxy-*` feature makes the DLL export the functions of a system DLL,
//! so it can be named after it. Rust cannot set export ordinals, and games
//! may import by ordinal, so the exports come from a module-definition file
//! (`proxy/<dll>.def`) that this script hands to the linker. Link arguments
//! of a dependency do not reach this crate's DLL, which is why the script
//! lives here and not in `ufathom-runtime`.
//!
//! The script also sets `cfg(ufathom_proxy)` when any `proxy-*` feature is on.

use std::path::PathBuf;

/// The Cargo feature variable of each preset and the file it exports from.
const PROXIES: &[(&str, &str)] = &[
{PROXIES}];

fn main() {
    println!("cargo::rerun-if-changed=build.rs");
    println!("cargo::rerun-if-changed=proxy");
    println!("cargo::rustc-check-cfg=cfg(ufathom_proxy)");

    let enabled: Vec<&str> = PROXIES
        .iter()
        .filter(|(variable, _)| std::env::var_os(variable).is_some())
        .map(|&(_, def)| def)
        .collect();
    let Some(&def) = enabled.first() else {
        return;
    };
    println!("cargo::rustc-cfg=ufathom_proxy");
    // Two features at once are a `compile_error!` in `src/dll.rs`.
    if enabled.len() > 1 {
        return;
    }

    let target_env = std::env::var("CARGO_CFG_TARGET_ENV").unwrap_or_default();
    let target_os = std::env::var("CARGO_CFG_TARGET_OS").unwrap_or_default();
    if target_os != "windows" || target_env != "msvc" {
        println!(
            "cargo::warning=the proxy features export from a .def file and need the x86_64-pc-windows-msvc target; this DLL exports nothing extra"
        );
        return;
    }
    let manifest_dir = std::env::var_os("CARGO_MANIFEST_DIR").map(PathBuf::from);
    let Some(manifest_dir) = manifest_dir else {
        println!("cargo::error=CARGO_MANIFEST_DIR is not set");
        return;
    };
    let path = manifest_dir.join(def);
    println!("cargo::rustc-cdylib-link-arg=/DEF:{}", path.display());
}
"#;

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_preset_has_a_def_file_with_all_its_exports() {
        let files = def_files();
        assert_eq!(files.len(), PRESETS.len());
        for (file, preset) in files.iter().zip(PRESETS) {
            assert!(file.path.ends_with(".def"), "{}", file.path);
            let entries = file
                .content
                .lines()
                .skip_while(|line| *line != "EXPORTS")
                .skip(1)
                .count();
            assert_eq!(entries, preset.exports.len(), "{}", file.path);
        }
    }

    #[test]
    fn the_def_file_maps_names_to_stubs_and_marks_ordinal_only_exports() {
        let winmm = PRESETS.iter().find(|p| p.dll == "winmm").unwrap();
        let text = winmm.def_file();
        assert!(
            text.contains("    mciExecute=ufathom_proxy_winmm_3 @3\n"),
            "{text}"
        );
        assert!(
            text.contains("    ufathom_proxy_winmm_2 @2 NONAME\n"),
            "{text}"
        );
        let dsound = PRESETS.iter().find(|p| p.dll == "dsound").unwrap();
        let text = dsound.def_file();
        assert!(
            text.contains("    DirectSoundCreate=ufathom_proxy_dsound_1 @1\n"),
            "{text}"
        );
        assert!(
            text.contains("    DllCanUnloadNow=ufathom_proxy_dsound_4 @4 PRIVATE\n"),
            "{text}"
        );
    }

    #[test]
    fn the_build_script_lists_every_feature() {
        let text = build_source();
        for preset in PRESETS {
            assert!(
                text.contains(&format!("\"{}\"", def_path(preset))),
                "{text}"
            );
        }
        assert!(!text.contains("{PROXIES}"));
    }

    #[test]
    fn two_features_at_once_are_a_compile_error() {
        let text = exclusive_features_check();
        assert!(text.contains("all(feature = \"proxy-version\", feature = \"proxy-winmm\")"));
        assert!(text.contains("compile_error!"));
    }
}
